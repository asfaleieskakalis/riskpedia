/**
 * Generates exactly 7 questions for ANY selected option:
 * - If 'general': picks 1 question from each of the 6 branches + 1 extra distinct question
 *   (so General Knowledge also has 7 questions across all insurance domains).
 * - If a specific coverage key: returns its 7 dedicated questions.
 */
export function generateQuizByTopic(
  topicKey: QuizTopicKey,
  isInitial = false
): QuizQuestion[] {
  if (topicKey === 'general') {
    const selected: QuizQuestion[] = [];
    const usedIds = new Set<string>();

    // 1 question from each of the 6 branches
    for (const branch of ALL_INSURANCE_BRANCHES) {
      const branchQuestions = QUIZ_QUESTION_BANK.filter((q) => q.branch === branch);
      let pick: QuizQuestion | undefined;

      if (isInitial) {
        if (branch === 'Ασφάλιση Αυτοκινήτου & Οχήματος') {
          pick = branchQuestions.find((q) => q.id === 'auto-4'); // Οδική Βοήθεια
        } else if (branch === 'Νομική Προστασία, Ταξιδιωτική, Σκάφη & Πατίνι/Ποδήλατο') {
          pick = branchQuestions.find((q) => q.id === 'other-4'); // Πατίνι & Ποδήλατο
        }
      }

      if (!pick) {
        pick = branchQuestions[Math.floor(Math.random() * branchQuestions.length)];
      }

      if (pick) {
        selected.push(pick);
        usedIds.add(pick.id);
      }
    }

    // Add a 7th distinct question (prioritize Νομική Προστασία or Ταξιδιωτική on initial)
    const remainingPool = QUIZ_QUESTION_BANK.filter((q) => !usedIds.has(q.id));
    if (remainingPool.length > 0) {
      let extraPick: QuizQuestion | undefined;
      if (isInitial) {
        extraPick = remainingPool.find((q) => q.id === 'other-1') || remainingPool[0];
      } else {
        extraPick = remainingPool[Math.floor(Math.random() * remainingPool.length)];
      }
      if (extraPick) {
        selected.push(extraPick);
      }
    }

    return selected;
  }

  return QUIZ_QUESTION_BANK.filter((q) => q.topicTags?.includes(topicKey)).slice(0, 7);
}
